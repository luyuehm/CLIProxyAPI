// Package tracer is the CPA data-plane auto-tracing channel (RIC-2508).
//
// It turns every model call the gateway already executes into a trace span
// and reports it to KEEPER's trace ingest endpoint, so applications that
// call models through the gateway get end-to-end tracing with zero business
// code changes. The channel is off by default: enabling it is an
// environment-variable decision, not a code change.
//
// The package has three parts:
//   - w3c.go: W3C Trace Context (traceparent) adoption, generation and
//     per-request context plumbing.
//   - reporter.go: a coreusage.Plugin that converts usage records into
//     KEEPER trace spans on an asynchronous, non-blocking path with a
//     bounded retry buffer (a lost trace must never block or fail a model
//     response).
//   - setup.go: env-var configuration, the gin middleware, and the
//     api.ServerOption wiring used by sdk/cliproxy/builder.go.
package tracer

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"strings"
)

const (
	// traceparentHeader is the W3C Trace Context header name.
	traceparentHeader = "Traceparent"
	// tracestateHeader is the W3C vendor-list header; passthrough only.
	tracestateHeader = "Tracestate"

	// traceIDHexLen / spanIDHexLen are the W3C-mandated hex widths.
	traceIDHexLen = 32
	spanIDHexLen  = 16

	// sampledFlag is the trace-flags byte for sampled traces.
	sampledFlag = "01"
	// notSampledFlag is the trace-flags byte for non-sampled traces.
	notSampledFlag = "00"
)

// TraceContext is the W3C Trace Context carried for one request. It is
// either adopted from an incoming traceparent header or generated by this
// node.
type TraceContext struct {
	// TraceID is the 128-bit trace identity (32 hex chars).
	TraceID string
	// ParentSpanID is the caller's span id carried by the incoming
	// header. Empty for self-generated contexts.
	ParentSpanID string
	// Sampled reports whether the incoming flags sampled bit was set.
	Sampled bool
	// Adopted is true when the context came from an incoming header rather
	// than being generated by this node.
	Adopted bool
	// Vendor is the passthrough tracestate value; empty when absent.
	Vendor string
}

// traceContextKey is the context key for the per-request TraceContext.
type traceContextKey struct{}

// WithTraceContext stores trace in ctx.
func WithTraceContext(ctx context.Context, trace *TraceContext) context.Context {
	if ctx == nil {
		return context.Background()
	}
	return context.WithValue(ctx, traceContextKey{}, trace)
}

// TraceContextFromContext returns the TraceContext stored in ctx, or nil
// when no middleware seeded one.
func TraceContextFromContext(ctx context.Context) *TraceContext {
	if ctx == nil {
		return nil
	}
	trace, _ := ctx.Value(traceContextKey{}).(*TraceContext)
	return trace
}

// ParseTraceparent validates a W3C traceparent value.
//
// Contract (W3C Trace Context, version 00):
//
//	traceparent = "00-" 32HEXDIG "-" 16HEXDIG "-" 2HEXDIG
//	              version trace-id    parent-id   flags
//
// All-zero trace-id or parent-id is invalid (the spec reserves those
// values): accepting them would collapse every context-less call into one
// trace. Unknown versions are rejected rather than guessed.
func ParseTraceparent(raw string) (*TraceContext, error) {
	trimmed := strings.TrimSpace(raw)
	if trimmed == "" {
		return nil, fmt.Errorf("empty traceparent")
	}
	parts := strings.Split(trimmed, "-")
	if len(parts) != 4 {
		return nil, fmt.Errorf("traceparent must have 4 segments, got %d", len(parts))
	}
	if parts[0] != "00" {
		return nil, fmt.Errorf("unsupported traceparent version %q", parts[0])
	}
	if len(parts[1]) != traceIDHexLen || len(parts[2]) != spanIDHexLen || len(parts[3]) != 2 {
		return nil, fmt.Errorf("traceparent segment widths must be 32/16/2 hex chars")
	}
	traceID, err := validateHexID(parts[1], traceIDHexLen)
	if err != nil {
		return nil, fmt.Errorf("traceparent trace-id: %w", err)
	}
	spanID, err := validateHexID(parts[2], spanIDHexLen)
	if err != nil {
		return nil, fmt.Errorf("traceparent parent-id: %w", err)
	}
	if traceID == strings.Repeat("0", traceIDHexLen) {
		return nil, fmt.Errorf("traceparent trace-id is all zeros")
	}
	if spanID == strings.Repeat("0", spanIDHexLen) {
		return nil, fmt.Errorf("traceparent parent-id is all zeros")
	}
	if _, err := validateHexID(parts[3], 2); err != nil {
		return nil, fmt.Errorf("traceparent flags: %w", err)
	}
	return &TraceContext{
		TraceID:      traceID,
		ParentSpanID: spanID,
		// The sampled bit is the least-significant bit of the two-digit
		// flags field: "01" = sampled, "00" = not sampled.
		Sampled: parts[3][1] == '1',
		Adopted: true,
	}, nil
}

func validateHexID(value string, width int) (string, error) {
	if len(value) != width {
		return "", fmt.Errorf("id width %d != %d", len(value), width)
	}
	// W3C reserves the id fields as lowercase hex; an uppercase id would
	// diverge from the lowercase ids the KEEPER side generates and would
	// break trace-id equality on ingest.
	normalized := strings.ToLower(value)
	if value != normalized {
		return "", fmt.Errorf("id must be lowercase hex")
	}
	if _, err := hex.DecodeString(value); err != nil {
		return "", fmt.Errorf("id is not hex: %w", err)
	}
	return value, nil
}

// GenerateTraceContext creates a fresh trace with a random trace-id.
func GenerateTraceContext() *TraceContext {
	return &TraceContext{
		TraceID: randomHex(traceIDHexLen),
		Sampled: true,
		Adopted: false,
	}
}

// GenerateSpanID returns a random span id at W3C width.
func GenerateSpanID() string { return randomHex(spanIDHexLen) }

func randomHex(hexChars int) string {
	buf := make([]byte, hexChars/2)
	if _, err := rand.Read(buf); err != nil {
		// crypto/rand failing means the platform has no source of
		// randomness; degrade to deterministic ids rather than silently
		// dropping traces.
		return strings.Repeat("0", hexChars)
	}
	return hex.EncodeToString(buf)
}

// FormatTraceparent renders the W3C header value this node should emit:
// the trace identity it carries plus the span id it is about to report.
// When no trace context is available it returns the empty string and the
// caller omits the header.
func FormatTraceparent(trace *TraceContext, spanID string) string {
	if trace == nil || trace.TraceID == "" {
		return ""
	}
	flags := notSampledFlag
	if trace.Sampled {
		flags = sampledFlag
	}
	if spanID == "" {
		spanID = GenerateSpanID()
	}
	return "00-" + trace.TraceID + "-" + spanID + "-" + flags
}

// Header returns the (traceparent, tracestate) pair this node echoes to the
// client. tracestate is passthrough-only: the vendor list is opaque to CPA.
func (t *TraceContext) Header(spanID string) (string, string) {
	if t == nil {
		return "", ""
	}
	return FormatTraceparent(t, spanID), t.Vendor
}
